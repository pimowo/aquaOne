inline const YoRadioGlyph& yoRadioGlyph(uint8_t code) {
  if (code >= 0x20 && code <= 0x7E) return YO_RADIO_ASCII_FONT[code - 0x20];
  if (code == 0x13) return YO_RADIO_SPEAKER;
  switch (code) {
    case 0xB7: return YO_RADIO_POLISH[0]; case 0xB8: return YO_RADIO_POLISH[1];
    case 0xB9: return YO_RADIO_POLISH[2]; case 0xBA: return YO_RADIO_POLISH[3];
    case 0xBB: return YO_RADIO_POLISH[4]; case 0xBC: return YO_RADIO_POLISH[5];
    case 0xBD: return YO_RADIO_POLISH[6]; case 0xBE: return YO_RADIO_POLISH[7];
    case 0xC4: return YO_RADIO_POLISH[8]; case 0xC0: return YO_RADIO_POLISH[9];
    case 0xC1: return YO_RADIO_POLISH[10]; case 0xC2: return YO_RADIO_POLISH[11];
    case 0xCB: return YO_RADIO_POLISH[11]; case 0xCF: return YO_RADIO_POLISH[13];
    case 0xD0: return YO_RADIO_POLISH[14]; case 0xD6: return YO_RADIO_POLISH[15];
    case 0xD7: return YO_RADIO_POLISH[16];
    case 0xBF: return YO_RADIO_POLISH[17];
    case 0xCC: return YO_RADIO_POLISH[12];
    default: return YO_RADIO_ASCII_FONT['?' - 0x20];
  }
}
